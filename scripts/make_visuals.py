"""Generate README visuals from the repo's own example data."""
import sys
from collections import Counter
from html import escape
from pathlib import Path

repo = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parent.parent
sys.path.insert(0, str(repo))
from engine import lint, scorecard  # noqa: E402

out = repo / "docs"
out.mkdir(exist_ok=True)
ex = repo / "examples" / "northwind"

rep = lint.lint_file(ex / "claude_baseline.md")
kinds = Counter(f.kind for f in rep.findings)
dec = Counter(r["decision"] for r in scorecard.decide(scorecard.load(ex / "content_inventory.csv")))
# share of voice from summary.md (generated by the tracker)
sov = []
for line in (ex / "ai-search" / "summary.md").read_text().splitlines():
    if line.startswith("| ") and line.endswith("% |") and not line.startswith("| Brand"):
        name, _, pct = [c.strip() for c in line.strip("|").split("|")]
        sov.append((name, int(pct.rstrip("%"))))

INK, MUTED, LINE, BG, ACCENT, ACCENT2, WARN = "#0f172a", "#64748b", "#e2e8f0", "#ffffff", "#0f766e", "#94a3b8", "#b45309"
FONT = "-apple-system,BlinkMacSystemFont,'Segoe UI',Helvetica,Arial,sans-serif"

W, H = 900, 360
s = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}" font-family="{FONT}">',
     f'<rect x="0.5" y="0.5" width="{W-1}" height="{H-1}" rx="14" fill="{BG}" stroke="{LINE}"/>']

def text(x, y, t, size=13, fill=INK, weight=400, anchor="start"):
    s.append(f'<text x="{x}" y="{y}" font-size="{size}" fill="{fill}" font-weight="{weight}" text-anchor="{anchor}">{escape(str(t))}</text>')

col = [32, 322, 612]
for i, (title, sub) in enumerate([("Generic Claude draft", "editorial lint score"),
                                  ("AI-search share of voice", "12 answers · ChatGPT + Perplexity"),
                                  ("Content scorecard", "12 pages, one decision each")]):
    text(col[i], 44, title, 15, INK, 600)
    text(col[i], 64, sub, 12, MUTED)
    if i:
        s.append(f'<line x1="{col[i]-22}" y1="32" x2="{col[i]-22}" y2="{H-32}" stroke="{LINE}"/>')

# Panel 1: score + findings
x = col[0]
text(x, 128, f"{rep.score}", 56, WARN, 700)
text(x + 74, 128, "/100", 20, MUTED, 500)
labels = {"banned": ("banned phrase", "banned phrases"), "tic": ("AI tic", "AI tics"),
          "unsourced-number": ("unsourced number", "unsourced numbers"),
          "vague": ("vague claim", "vague claims"), "superlative": ("unearned superlative", "unearned superlatives")}
y = 168
for k in ["banned", "tic", "unsourced-number", "vague", "superlative"]:
    n = kinds.get(k, 0)
    s.append(f'<rect x="{x}" y="{y-11}" width="{max(6, n*16)}" height="14" rx="3" fill="{WARN}" opacity="0.85"/>')
    text(x + max(6, n*16) + 8, y, f"{n}  {labels[k][0] if n == 1 else labels[k][1]}", 12, INK)
    y += 26
text(x, y + 14, f"{len(rep.findings)} findings in {rep.words} words", 12, MUTED)

# Panel 2: share of voice bars
x = col[1]
y = 112
maxw = 190
for name, pct in sov:
    us = name == sov[0][0]
    text(x, y, name, 13, INK, 600 if us else 400)
    s.append(f'<rect x="{x}" y="{y+8}" width="{maxw}" height="16" rx="4" fill="{LINE}"/>')
    s.append(f'<rect x="{x}" y="{y+8}" width="{maxw*pct/100:.0f}" height="16" rx="4" fill="{ACCENT if us else ACCENT2}"/>')
    text(x + maxw + 10, y + 21, f"{pct}%", 13, INK, 600)
    y += 58
text(x, y + 4, "Absent from 6 high-priority buyer questions", 12, MUTED)

# Panel 3: decisions
x = col[2]
order = [("PROTECT", "#0f766e"), ("REFRESH", "#2563eb"), ("CONSOLIDATE", "#7c3aed"), ("KILL", "#b91c1c"), ("WATCH", "#94a3b8")]
total = sum(dec.values())
barw, cx = 256, x
for name, color in order:
    w = barw * dec[name] / total
    s.append(f'<rect x="{cx:.1f}" y="96" width="{w:.1f}" height="22" fill="{color}"/>')
    cx += w
y = 150
for name, color in order:
    s.append(f'<rect x="{x}" y="{y-10}" width="12" height="12" rx="3" fill="{color}"/>')
    text(x + 20, y, name.title(), 13, INK)
    text(x + 150, y, dec[name], 13, INK, 600, "end")
    y += 26
text(x, y + 14, "Decided by pipeline per $, decay and overlap", 12, MUTED)

s.append("</svg>")
(out / "dashboard.svg").write_text("\n".join(s) + "\n")

# Dark variant for the landing page
dark = "\n".join(s) + "\n"
for light, dk in [("#ffffff", "#14161b"), ("#0f172a", "#f4f4f5"), ("#64748b", "#a1a1aa"),
                  ("#e2e8f0", "#2a2e37"), ("#0f766e", "#2dd4bf"), ("#b45309", "#fbbf24"),
                  ("#94a3b8", "#52525b")]:
    dark = dark.replace(f'"{light}"', f'"{dk}"')
(out / "dashboard-dark.svg").write_text(dark)

# ---------- animated terminal ----------
lines = [
    ("cmd", "python -m engine lint examples/northwind/claude_baseline.md"),
    ("out", f"Score: {rep.score}/100 · {rep.words} words · {len(rep.findings)} findings"),
    ("cmd", "python -m engine ai-search score examples/northwind/ai-search"),
    ("out", "scored 12 answers, 6 high-priority gaps. See summary.md"),
    ("cmd", "python -m engine scorecard examples/northwind/content_inventory.csv"),
    ("out", f"PROTECT {dec['PROTECT']} · REFRESH {dec['REFRESH']} · CONSOLIDATE {dec['CONSOLIDATE']} · KILL {dec['KILL']} · WATCH {dec['WATCH']}"),
    ("cmd", "python -m engine run runs/demo brief"),
    ("err", "Stopped: Pick an angle first: write it to chosen_angle.md in the run folder."),
]
TW, LH, TOP = 900, 30, 64
TH = TOP + LH * (len(lines) - 1) + 28
step = 1.2
total_t = step * len(lines) + 4
t = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{TW}" height="{TH}" viewBox="0 0 {TW} {TH}" font-family="ui-monospace,SFMono-Regular,Menlo,Consolas,monospace">',
     "<style>",
     f".l{{opacity:0;animation:show {total_t}s infinite}}",
     "@keyframes show{0%{opacity:0}2%{opacity:1}92%{opacity:1}100%{opacity:0}}",
     "</style>",
     f'<rect width="{TW}" height="{TH}" rx="12" fill="#0b1220"/>',
     '<circle cx="24" cy="22" r="6" fill="#ef4444"/><circle cx="44" cy="22" r="6" fill="#f59e0b"/><circle cx="64" cy="22" r="6" fill="#22c55e"/>',
     f'<text x="{TW/2}" y="27" font-size="12" fill="#64748b" text-anchor="middle">content-engine</text>']
colors = {"cmd": "#e2e8f0", "out": "#5eead4", "err": "#fbbf24"}
for i, (kind, txt) in enumerate(lines):
    y = TOP + i * LH
    delay = i * step
    prefix = "$ " if kind == "cmd" else "  "
    pc = '<tspan fill="#64748b">$ </tspan>' if kind == "cmd" else '<tspan>  </tspan>'
    t.append(f'<text class="l" style="animation-delay:{delay:.1f}s" x="24" y="{y}" font-size="14" fill="{colors[kind]}">{pc}{escape(txt)}</text>')
t.append("</svg>")
(out / "demo.svg").write_text("\n".join(t) + "\n")
print(f"wrote {out / 'dashboard.svg'} and {out / 'demo.svg'}")
